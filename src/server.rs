//!
//! Mirror of `com.softtek.mcp.CobolMcpServer` / `JavaMcpServer`.
//! `start()` registers the tools **one by one** into a `Vec<Box<dyn McpTool>>`,
//! builds the `ServerHandler`, and mounts the stdio transport.
//!
//! Registration is verbose by design — we want adding a new tool
//! to imply a visible line in `start()`, just like in the other 3 MCPs.

