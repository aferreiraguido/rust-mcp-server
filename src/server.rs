// Includes the version generated by build.rs (`pub const VERSION: &str = "..."`).
include!(concat!(env!("OUT_DIR"), "/version.rs"));

pub struct RustMcpServer {
    pub manager: Arc<ProjectManager>,
}

impl RustMcpServer {
    pub fn new(manager: Arc<ProjectManager>) -> Self {
        Self { manager }
    }

    /// Builds and starts the server. Blocks until the host closes
    /// the process or stdio drops.
    pub async fn start(self) -> anyhow::Result<()> {
        info!(version = VERSION, "rust-mcp-server starting");

        // stdio transport. rmcp expects a pair (AsyncRead, AsyncWrite).
        let transport = rmcp::transport::io::stdio();

        // `.serve(transport)` comes from `ServiceExt`. Returns a `RunningService`.
        let server = self
            .serve(transport)
            .await
            .with_context(|| format!("failed to start MCP server (version {})", VERSION))?;

        info!("rust-mcp-server started, awaiting client on stdio");

        // Blocks until shutdown.
        let quit_reason = server.waiting().await?;
        info!(?quit_reason, "rust-mcp-server shutting down");
        Ok(())
    }

    /// Builds the list of tool instances. Single registration point.
    /// (Mirror of `List.of(new XTool(manager).build(), ...)` in Java.)
    fn build_tools(&self) -> Vec<Box<dyn McpTool>> {
        vec![
            Box::new(ListLoadedProjectsTool::new(self.manager.clone())),
            // Source management
            Box::new(LoadRustProjectTool::new(self.manager.clone())),
            Box::new(UnloadRustProjectTool::new(self.manager.clone())),
            Box::new(ProjectMetadataTool::new(self.manager.clone())),
            Box::new(InspectBuildConfigTool::new(self.manager.clone())),
            // Cargo-level
            Box::new(ListCratesTool::new(self.manager.clone())),
            Box::new(ListDependenciesTool::new(self.manager.clone())),
            Box::new(ListCargoFeaturesTool::new(self.manager.clone())),
            Box::new(ProgramSummaryTool::new(self.manager.clone())),
            // File ops
            Box::new(GetFileContentTool::new(self.manager.clone())),
            Box::new(SearchSourceTool::new(self.manager.clone())),
            // Source listings (syn-based)
            Box::new(ListFunctionsTool::new(self.manager.clone())),
            Box::new(ListStructsTool::new(self.manager.clone())),
            Box::new(ListEnumsTool::new(self.manager.clone())),
            Box::new(ListTraitsTool::new(self.manager.clone())),
            Box::new(ListImplsTool::new(self.manager.clone())),
            Box::new(ListModulesTool::new(self.manager.clone())),
            Box::new(ListMacrosTool::new(self.manager.clone())),
            // Inspections
            Box::new(InspectFunctionTool::new(self.manager.clone())),
            Box::new(InspectStructTool::new(self.manager.clone())),
            Box::new(InspectEnumTool::new(self.manager.clone())),
            Box::new(InspectTraitTool::new(self.manager.clone())),
            // Cross-references
            Box::new(ValidateCodeReferenceTool::new(self.manager.clone())),
            Box::new(FindReferencesTool::new(self.manager.clone())),
            Box::new(FunctionCallersTool::new(self.manager.clone())),
            // ASG integration (iter 3)
            Box::new(AnalysisSummaryTool::new(self.manager.clone())),
            // Semantic queries (iter 3.5)
            Box::new(ResolveTypeTool::new(self.manager.clone())),
            // Semantic queries (iter 3.6 — the rest of the ASG tools)
            Box::new(FindImplementationsTool::new(self.manager.clone())),
            Box::new(GetTypeHierarchyTool::new(self.manager.clone())),
            Box::new(FunctionCallGraphTool::new(self.manager.clone())),
            Box::new(StructFieldXrefTool::new(self.manager.clone())),
            // Bug-hunt (iter 4)
            Box::new(FindUnsafeBlocksTool::new(self.manager.clone())),
            Box::new(FindUnwrapPatternsTool::new(self.manager.clone())),
            Box::new(FindUncheckedPatternsTool::new(self.manager.clone())),
            Box::new(FindPanicSitesTool::new(self.manager.clone())),
            Box::new(FindDeadCodeTool::new(self.manager.clone())),
            // Bug-hunt (iter 6+)
            Box::new(FindUnusedDependenciesTool::new(self.manager.clone())),
        ]
    }
}

impl ServerHandler for RustMcpServer {
    fn get_info(&self) -> ServerInfo {
        let capabilities = ServerCapabilities::builder().enable_tools().build();

        ServerInfo::new(capabilities)
            .with_server_info(
                Implementation::new("rust-mcp-server", VERSION).with_title("Rust MCP Server"),
            )
            .with_instructions(
                "Deterministic Rust code analysis via ASG (rust-analyzer). \
                 Ground truth for AI agents — no hallucination.",
            )
    }

    async fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListToolsResult, ErrorData> {
        let tools = self.build_tools();

        let tool_specs: Vec<Tool> = tools
            .iter()
            .map(|t| {
                let input_obj: serde_json::Map<String, serde_json::Value> =
                    t.input_schema().as_object().cloned().unwrap_or_default();
                Tool::new(t.name(), t.description(), input_obj)
            })
            .collect();

        Ok(ListToolsResult::with_all_items(tool_specs))
    }

    async fn call_tool(
        &self,
        request: CallToolRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<CallToolResult, ErrorData> {
        let tools = self.build_tools();

        let tool = tools
            .iter()
            .find(|t| t.name() == request.name.as_ref())
            .ok_or_else(|| {
                ErrorData::invalid_params(
                    format!("Unknown tool: '{}'", request.name),
                    Some(serde_json::json!({
                        "available": tools.iter().map(|t| t.name()).collect::<Vec<_>>()
                    })),
                )
            })?;

        // Arguments: rmcp 2.2 exposes `request.arguments` as `Option<JsonObject>`.
        let args = request
            .arguments
            .map(|m| serde_json::Value::Object(m.into_iter().collect()))
            .unwrap_or_else(|| serde_json::Value::Object(Default::default()));

        tool.call(args).await
    }

    /// opencode sends `notifications/initialized` as REQUEST (with JSON-RPC id)
    /// instead of as notification (without id). `rmcp` 2.2 only handles it as
    /// notification, so when it arrives as a request it falls here.
    /// If we return an error, opencode may not inject the server tools.
    async fn on_custom_request(
        &self,
        request: CustomRequest,
        _context: RequestContext<RoleServer>,
    ) -> Result<CustomResult, ErrorData> {
        if request.method == "notifications/initialized" {
            return Ok(CustomResult(serde_json::json!({})));
        }
        Err(ErrorData::invalid_params(
            format!("Unknown method: '{}'", request.method),
            None,
        ))
    }
}
